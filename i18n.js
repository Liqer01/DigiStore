const SUPPORTED_LANGUAGES = [
  { code: 'tr', badge: 'TR', name: 'Türkçe' },
  { code: 'en', badge: 'GB', name: 'English' },
  { code: 'az', badge: 'AZ', name: 'Azərbaycan' },
  { code: 'fr', badge: 'FR', name: 'Français' },
  { code: 'de', badge: 'DE', name: 'Deutsch' },
  { code: 'zh', badge: 'CN', name: '中文' },
  { code: 'ru', badge: 'RU', name: 'Русский' }
];

let currentLang = 'tr';

function getStoredLanguage() {
  try {
    const saved = localStorage.getItem('closy_language');
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch (e) {}
  return 'tr';
}

function setLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) langCode = 'tr';
  currentLang = langCode;
  try {
    localStorage.setItem('closy_language', langCode);
  } catch (e) {}

  document.documentElement.lang = langCode;

  // Header Butonunu Güncelle
  const activeLangObj = SUPPORTED_LANGUAGES.find(l => l.code === langCode) || SUPPORTED_LANGUAGES[0];
  const langBadgeEl = document.getElementById('currentLangBadge');
  if (langBadgeEl) {
    langBadgeEl.textContent = activeLangObj.badge;
  }

  // Dropdown İçi Aktif Seçim ve Tik İşaretlerini Güncelle
  renderLanguageDropdown();

  // Tüm data-i18n etiketli elemanları güncelle
  applyTranslations();

  // Dropdown'ı kapat
  const dd = document.getElementById('langDropdownMenu');
  if (dd) dd.style.display = 'none';
}

function applyTranslations() {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.tr;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Kategori filtrelerini yeniden render et (eğer fonksiyon varsa)
  if (typeof renderCategoryFilters === 'function') {
    renderCategoryFilters();
  }
  if (typeof renderStorefrontProducts === 'function') {
    renderStorefrontProducts();
  }
}

function t(key, fallback = '') {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.tr;
  return dict[key] || fallback || key;
}

function toggleLangDropdown(e) {
  if (e) {
    e.stopPropagation();
    e.preventDefault();
  }
  const dd = document.getElementById('langDropdownMenu');
  if (!dd) return;
  const isHidden = dd.style.display === 'none' || !dd.style.display;
  dd.style.display = isHidden ? 'block' : 'none';
}

function renderLanguageDropdown() {
  const listEl = document.getElementById('langDropdownList');
  if (!listEl) return;

  listEl.innerHTML = SUPPORTED_LANGUAGES.map(lang => {
    const isSelected = lang.code === currentLang;
    return `
      <div onclick="setLanguage('${lang.code}')" style="
        display: flex;
        align-items: center;
        justify-content: space-between;
        padding: 9px 12px;
        border-radius: 9px;
        cursor: pointer;
        background: ${isSelected ? 'rgba(255, 120, 30, 0.12)' : 'transparent'};
        color: ${isSelected ? '#ffffff' : '#a1a1aa'};
        transition: background 0.15s ease, color 0.15s ease;
      " onmouseover="if('${lang.code}' !== '${currentLang}') { this.style.background='rgba(255,255,255,0.06)'; this.style.color='#fff'; }" onmouseout="if('${lang.code}' !== '${currentLang}') { this.style.background='transparent'; this.style.color='#a1a1aa'; }">
        <div style="display: flex; align-items: center; gap: 10px;">
          <span style="
            font-size: 11.5px;
            font-weight: 800;
            color: ${isSelected ? '#ff9f0a' : '#71717a'};
            width: 22px;
            letter-spacing: 0.5px;
          ">${lang.badge}</span>
          <span style="font-size: 13px; font-weight: ${isSelected ? '600' : '500'};">${lang.name}</span>
        </div>
        ${isSelected ? `
          <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="#ff9f0a" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round">
            <polyline points="20 6 9 17 4 12"></polyline>
          </svg>
        ` : ''}
      </div>
    `;
  }).join('');
}

// Global Dışarı Tıklama ile Dropdown'ı Kapat
document.addEventListener('click', (e) => {
  const dd = document.getElementById('langDropdownMenu');
  const btn = document.getElementById('langPickerBtn');
  if (dd && btn && !btn.contains(e.target) && !dd.contains(e.target)) {
    dd.style.display = 'none';
  }
});

// Sayfa yüklendiğinde otomatik başlat
document.addEventListener('DOMContentLoaded', () => {
  currentLang = getStoredLanguage();
  renderLanguageDropdown();
  setLanguage(currentLang);
});
